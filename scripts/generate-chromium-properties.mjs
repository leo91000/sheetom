import { writeFile } from "node:fs/promises";

import * as csstree from "css-tree";
import { chromium } from "playwright";

const browser = await chromium.launch({ headless: true });

try {
  const page = await browser.newPage();
  const cssTreeCandidates = Object.keys(csstree.lexer.properties).filter(
    name => !name.startsWith("--"),
  );
  const result = await page.evaluate(candidates => {
    function namedPropertyToCSS(property) {
      if (property === "cssFloat") return "float";
      let cssName = property.replace(
        /[A-Z]/g,
        character => `-${character.toLowerCase()}`,
      );
      if (/^(webkit|moz|ms|o)-/.test(cssName)) cssName = `-${cssName}`;
      return cssName;
    }

    const names = new Set(candidates);
    for (const property in document.documentElement.style) {
      names.add(namedPropertyToCSS(property));
    }

    const properties = [...names]
      .filter(name => CSS.supports(name, "initial"))
      .sort();
    const shorthands = {};
    for (const name of properties) {
      const style = document.createElement("div").style;
      style.setProperty(name, "var(--sheetom-probe)");
      const longhands = Array.from(style);
      if (longhands.length <= 1 && longhands[0] === name) continue;
      if (longhands.length === 0) continue;
      shorthands[name] = longhands;
    }

    return {
      userAgent: navigator.userAgent,
      properties,
      shorthands,
    };
  }, cssTreeCandidates);

  const source = `// Generated by npm run generate:properties. Do not edit manually.\n` +
    `export const chromiumPropertyBaseline = ${JSON.stringify(result.userAgent)};\n\n` +
    `export const chromiumSupportedProperties = new Set(${JSON.stringify(result.properties, null, 2)});\n\n` +
    `export const chromiumShorthandLonghands: Readonly<Record<string, readonly string[]>> = ${JSON.stringify(result.shorthands, null, 2)};\n`;

  await writeFile(new URL("../src/chromium-properties.ts", import.meta.url), source);
  console.log(
    `Wrote ${result.properties.length} properties and ${Object.keys(result.shorthands).length} shorthands from ${result.userAgent}`,
  );
} finally {
  await browser.close();
}
