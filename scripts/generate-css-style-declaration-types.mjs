import { readFile, writeFile } from "node:fs/promises";

import { chromiumSupportedProperties } from "../src/chromium-properties.ts";

const outputUrl = new URL(
  "../src/generated/css-style-declaration-properties.ts",
  import.meta.url,
);
const mode = process.argv[2] ?? "--check";

if (!["--check", "--record"].includes(mode)) {
  throw new Error(
    "Usage: generate-css-style-declaration-types.mjs [--check|--record]",
  );
}

function namedProperty(property) {
  const parts = property.split("-").filter(Boolean);
  if (parts.length === 0) return property;
  const [first, ...rest] = parts;
  return first + rest
    .map(part => `${part[0]?.toUpperCase() ?? ""}${part.slice(1)}`)
    .join("");
}

const properties = new Set(
  [...chromiumSupportedProperties].map(namedProperty),
);
properties.add("cssFloat");

const lines = [
  "// Generated by npm run record:css-style-declaration-types. Do not edit manually.",
  "/** Named CSS properties supported by the pinned Chromium compatibility baseline. */",
  "export interface CSSStyleDeclarationNamedProperties {",
  ...[...properties]
    .sort((left, right) => left.localeCompare(right))
    .map(property => `  ${property}: string;`),
  "}",
  "",
];
const serialized = lines.join("\n");

if (mode === "--record") {
  await writeFile(outputUrl, serialized);
  console.log(`Recorded ${properties.size} named CSS declaration properties.`);
} else {
  const current = await readFile(outputUrl, "utf8");
  if (current !== serialized) {
    throw new Error(
      "CSSStyleDeclaration named property types drifted; review the diff and run " +
      "npm run record:css-style-declaration-types to accept it",
    );
  }
  console.log(`Verified ${properties.size} named CSS declaration properties.`);
}
